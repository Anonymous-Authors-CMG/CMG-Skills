let current: 'en' | 'zh' = 'en';

/** Set from `vscode.env.language` on activation. */
export function setLanguage(vscodeLanguage: string | undefined): void {
    current = (vscodeLanguage ?? '').toLowerCase().startsWith('zh') ? 'zh' : 'en';
}
export function uiLanguage(): 'en' | 'zh' { return current; }

export function t(key: string, ...args: (string | number)[]): string {
    const template = (current === 'zh' ? zh[key] : undefined) ?? en[key] ?? key;
    return template.replace(/\{(\d+)\}/g, (_m, i) => String(args[Number(i)] ?? ''));
}

/** The subset the webview needs, as raw templates. */
export function webviewStrings(): Record<string, string> {
    const dict = current === 'zh' ? { ...en, ...zh } : en;
    return Object.fromEntries(Object.entries(dict).filter(([k]) => k.startsWith('ui.') || k.startsWith('conf.')));
}
